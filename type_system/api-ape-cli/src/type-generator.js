/**
 * @fileoverview TypeScript Type Generator
 *
 * Generates TypeScript declarations from api-ape schema.
 */

/**
 * Convert TypeDefinition to TypeScript string
 *
 * @param {object} typeDef - Type definition object
 * @returns {string} TypeScript type string
 */
function typeDefToString(typeDef) {
  if (!typeDef) return "any";

  switch (typeDef.kind) {
    case "primitive":
      return typeDef.name;

    case "reference":
      if (typeDef.name === "Object") return "Record<string, any>";
      return typeDef.name;

    case "array":
      return `${typeDefToString(typeDef.items)}[]`;

    case "union":
      return typeDef.types.map(typeDefToString).join(" | ");

    case "promise":
      return `Promise<${typeDefToString(typeDef.resolves)}>`;

    case "object":
      if (!typeDef.properties || Object.keys(typeDef.properties).length === 0) {
        return "Record<string, any>";
      }
      const props = Object.entries(typeDef.properties)
        .map(([name, prop]) => {
          const optional = prop.optional ? "?" : "";
          const type = typeDefToString(prop);
          const comment = prop.description
            ? `/** ${prop.description} */\n    `
            : "";
          return `${comment}${name}${optional}: ${type}`;
        })
        .join(";\n    ");
      return `{\n    ${props}\n  }`;

    default:
      return "any";
  }
}

/**
 * Group endpoints by namespace
 *
 * @param {Array} endpoints - Array of endpoint objects
 * @returns {Map} Map of namespace to endpoints
 */
function groupByNamespace(endpoints) {
  const groups = new Map();

  for (const endpoint of endpoints) {
    const parts = endpoint.path.split("/");
    const namespace = parts[0];
    const subPath = parts.slice(1).join("/");

    if (!groups.has(namespace)) {
      groups.set(namespace, []);
    }

    groups.get(namespace).push({
      ...endpoint,
      subPath,
      isRoot: parts.length === 1,
    });
  }

  return groups;
}

/**
 * Convert a string to PascalCase for TypeScript interface names
 *
 * @param {string} str - Input string
 * @returns {string} PascalCase string
 */
function toPascalCase(str) {
  return str
    .split(/[-_]/)
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join("");
}

/**
 * Generate TypeScript declarations from schema
 *
 * @param {object} schema - The schema
 * @returns {string} TypeScript declaration content
 */
function generateTypes(schema) {
  const namespaces = groupByNamespace(schema.endpoints);
  const lines = [];

  lines.push("// Auto-generated by @api-ape/cli");
  lines.push(`// Generated at: ${new Date(schema.timestamp).toISOString()}`);
  lines.push(`// Schema version: ${schema.version}`);
  lines.push("");
  lines.push("import 'api-ape';");
  lines.push("");
  lines.push("declare module 'api-ape' {");

  // Generate interface for each namespace
  for (const [namespace, endpoints] of namespaces) {
    const interfaceName = `${toPascalCase(namespace)}Endpoints`;

    lines.push("");
    lines.push(`  /** Endpoints under /${namespace} */`);
    lines.push(`  interface ${interfaceName} {`);

    for (const endpoint of endpoints) {
      const inputType = typeDefToString(endpoint.input);
      const outputType = typeDefToString(endpoint.output);

      // Add JSDoc
      if (endpoint.description) {
        lines.push(`    /**`);
        lines.push(`     * ${endpoint.description}`);
        lines.push(`     * @endpoint /${endpoint.path}`);
        lines.push(`     */`);
      }

      if (endpoint.isRoot) {
        lines.push(
          `    (data${endpoint.input ? "" : "?"}: ${inputType}): Promise<${outputType}>;`
        );
      } else {
        const methodName = endpoint.subPath.split("/").pop();
        lines.push(
          `    ${methodName}(data${endpoint.input ? "" : "?"}: ${inputType}): Promise<${outputType}>;`
        );
      }
    }

    lines.push("  }");
  }

  // Generate main ApiEndpoints interface
  lines.push("");
  lines.push("  /** All api-ape endpoints */");
  lines.push("  interface ApiEndpoints {");

  for (const [namespace] of namespaces) {
    const interfaceName = `${toPascalCase(namespace)}Endpoints`;
    // Quote the key if it contains special characters
    const key = /^[a-zA-Z_$][a-zA-Z0-9_$]*$/.test(namespace)
      ? namespace
      : `'${namespace}'`;
    lines.push(`    ${key}: ${interfaceName} & ApiEndpoints;`);
  }

  lines.push("  }");

  // Override default export
  lines.push("");
  lines.push("  /** Typed api-ape client */");
  lines.push("  const api: ApiEndpoints & {");
  lines.push(
    "    on<T = any>(type: string, handler: (msg: { type: string; data: T }) => void): void;"
  );
  lines.push(
    "    onConnectionChange(handler: (state: ConnectionState) => void): () => void;"
  );
  lines.push("    readonly transport: 'websocket' | 'polling' | null;");
  lines.push("  };");
  lines.push("");
  lines.push("  export default api;");
  lines.push("}");
  lines.push("");

  return lines.join("\n");
}

module.exports = {
  generateTypes,
  typeDefToString,
  groupByNamespace,
  toPascalCase,
};
