/**
 * @fileoverview TypeScript Declaration Generator for api-ape
 *
 * Generates .d.ts files from api-ape schema that augment the api-ape module
 * to provide IntelliSense and type checking.
 */

/**
 * Convert a TypeDefinition to a TypeScript type string
 *
 * @param {TypeDefinition} typeDef - The type definition
 * @returns {string} TypeScript type string
 */
function typeDefToString(typeDef) {
  if (!typeDef) return "any";

  switch (typeDef.kind) {
    case "primitive":
      return typeDef.name;

    case "reference":
      // Map common JSDoc types to TS equivalents
      if (typeDef.name === "Object") return "Record<string, any>";
      return typeDef.name;

    case "array":
      const itemType = typeDefToString(typeDef.items);
      return `${itemType}[]`;

    case "union":
      return typeDef.types.map(typeDefToString).join(" | ");

    case "promise":
      return `Promise<${typeDefToString(typeDef.resolves)}>`;

    case "object":
      if (!typeDef.properties || Object.keys(typeDef.properties).length === 0) {
        return "Record<string, any>";
      }
      const props = Object.entries(typeDef.properties)
        .map(([name, prop]) => {
          const optional = prop.optional ? "?" : "";
          const type = typeDefToString(prop);
          const comment = prop.description
            ? `/** ${prop.description} */\n    `
            : "";
          return `${comment}${name}${optional}: ${type}`;
        })
        .join(";\n    ");
      return `{\n    ${props}\n  }`;

    case "literal":
      // String or number literal type
      if (typeof typeDef.value === "string") {
        return `"${typeDef.value}"`;
      }
      return String(typeDef.value);

    case "record":
      // Index signature / Record type
      const keyType = typeDefToString(typeDef.key) || "string";
      const valueType = typeDefToString(typeDef.value) || "any";
      return `Record<${keyType}, ${valueType}>`;

    case "any":
    default:
      return "any";
  }
}

/**
 * Convert endpoint path to a valid TypeScript identifier
 *
 * @param {string} path - Endpoint path like "users/profile"
 * @returns {string} Valid identifier like "usersProfile"
 */
function pathToIdentifier(path) {
  return path
    .split("/")
    .map((part, i) =>
      i === 0 ? part : part.charAt(0).toUpperCase() + part.slice(1)
    )
    .join("");
}

/**
 * Group endpoints by their top-level namespace
 *
 * @param {Endpoint[]} endpoints - Array of endpoints
 * @returns {Map<string, Endpoint[]>} Map of namespace to endpoints
 */
function groupByNamespace(endpoints) {
  const groups = new Map();

  for (const endpoint of endpoints) {
    const parts = endpoint.path.split("/");
    const namespace = parts[0];
    const subPath = parts.slice(1).join("/");

    if (!groups.has(namespace)) {
      groups.set(namespace, []);
    }

    groups.get(namespace).push({
      ...endpoint,
      subPath,
      isRoot: parts.length === 1,
    });
  }

  return groups;
}

/**
 * Generate a JSDoc comment for an endpoint
 *
 * @param {Endpoint} endpoint - The endpoint
 * @returns {string} JSDoc comment string
 */
function generateJSDocComment(endpoint) {
  const lines = ["/**"];

  if (endpoint.description) {
    lines.push(` * ${endpoint.description}`);
    lines.push(" *");
  }

  lines.push(` * @endpoint /${endpoint.path}`);

  if (endpoint.throws && endpoint.throws.length > 0) {
    for (const t of endpoint.throws) {
      lines.push(` * @throws ${t}`);
    }
  }

  lines.push(" */");
  return lines.join("\n");
}

/**
 * Generate TypeScript declarations from schema
 *
 * @param {ApeSchema} schema - The schema
 * @returns {string} TypeScript declaration file content
 */
function generateTypeDeclarations(schema) {
  const namespaces = groupByNamespace(schema.endpoints);
  const lines = [];

  // Header
  lines.push("// Auto-generated by @api-ape/schema");
  lines.push(`// Generated at: ${new Date(schema.timestamp).toISOString()}`);
  lines.push(`// Schema version: ${schema.version}`);
  lines.push("");
  lines.push("import 'api-ape';");
  lines.push("");
  lines.push("declare module 'api-ape' {");

  // Generate interface for each namespace
  for (const [namespace, endpoints] of namespaces) {
    const interfaceName = `${namespace.charAt(0).toUpperCase() + namespace.slice(1)}Endpoints`;

    lines.push("");
    lines.push(`  /** Endpoints under /${namespace} */`);
    lines.push(`  interface ${interfaceName} {`);

    for (const endpoint of endpoints) {
      const inputType = typeDefToString(endpoint.input);
      const outputType = typeDefToString(endpoint.output);

      // Add JSDoc
      const jsdoc = generateJSDocComment(endpoint);
      lines.push(
        jsdoc
          .split("\n")
          .map((l) => `    ${l}`)
          .join("\n")
      );

      if (endpoint.isRoot) {
        // Root endpoint - callable directly
        lines.push(`    (data${endpoint.input ? "" : "?"}: ${inputType}): Promise<${outputType}>;`);
      } else {
        // Nested endpoint - property
        const methodName = endpoint.subPath.split("/").pop();
        lines.push(`    ${methodName}(data${endpoint.input ? "" : "?"}: ${inputType}): Promise<${outputType}>;`);
      }
    }

    lines.push("  }");
  }

  // Generate the main ApiEndpoints interface that combines all namespaces
  lines.push("");
  lines.push("  /** All api-ape endpoints */");
  lines.push("  interface ApiEndpoints {");

  for (const [namespace, endpoints] of namespaces) {
    const interfaceName = `${namespace.charAt(0).toUpperCase() + namespace.slice(1)}Endpoints`;
    const rootEndpoint = endpoints.find((e) => e.isRoot);

    if (rootEndpoint) {
      // Namespace is both callable and has nested properties
      lines.push(`    ${namespace}: ${interfaceName} & ApiEndpoints;`);
    } else {
      // Namespace only has nested properties
      lines.push(`    ${namespace}: ${interfaceName} & ApiEndpoints;`);
    }
  }

  lines.push("  }");

  // Override the default export
  lines.push("");
  lines.push("  /** Typed api-ape client */");
  lines.push("  const api: ApiEndpoints & {");
  lines.push("    on<T = any>(type: string, handler: (msg: { type: string; data: T }) => void): void;");
  lines.push("    onConnectionChange(handler: (state: ConnectionState) => void): () => void;");
  lines.push("    readonly transport: 'websocket' | 'polling' | null;");
  lines.push("  };");
  lines.push("");
  lines.push("  export default api;");
  lines.push("}");
  lines.push("");

  return lines.join("\n");
}

module.exports = {
  generateTypeDeclarations,
  typeDefToString,
  groupByNamespace,
};
